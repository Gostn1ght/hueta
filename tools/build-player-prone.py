"""Author in-place prone cycles on the game's 47-bone human skeleton.

Run in portable Blender, with --template <base actor OGF>, --addons <xray
addon directory>, --output <OMF>. No existing NPC animations are replaced.
The stock 'walk_fwd_crawl' was inspected and rejected: it is upright wounded
walking, with a head height above 1.3 m, not a prone locomotion cycle.
"""
import argparse
import json
import math
import sys
import importlib.util
from pathlib import Path

import addon_utils
import bpy
from mathutils import Matrix, Quaternion, Vector

p=argparse.ArgumentParser()
p.add_argument('--template',type=Path,required=True)
p.add_argument('--addons',type=Path,required=True)
p.add_argument('--output',type=Path,required=True)
p.add_argument('--partitions',type=Path,default=Path(__file__).resolve().parents[1]/'scripts/netcoop-overlay/client/meshes/actors/stalker_animation.omf')
args=p.parse_args(sys.argv[sys.argv.index('--')+1:])
sys.path.insert(0,str(args.addons.resolve()))
bpy.ops.wm.read_factory_settings(use_empty=True)
addon_utils.enable('io_scene_xray',default_set=True,persistent=False)
bpy.ops.xray_import.ogf(directory=str(args.template.parent),files=[{'name':args.template.name}],import_motions=False)
rig=next(o for o in bpy.context.scene.objects if o.type=='ARMATURE')
assert len(rig.data.bones)==47
spec=importlib.util.spec_from_file_location('merge',Path(__file__).resolve().parents[1]/'scripts/tools/merge-player-anims.py')
merge=importlib.util.module_from_spec(spec);spec.loader.exec_module(merge)
for name,bones in merge.parse(args.partitions)['parts']:
    collection=rig.data.collections.new(name)
    for name,_ in bones:collection.assign(rig.data.bones[name])
rig.animation_data_create()
rig.xray.motions_collection.clear()
for action in list(bpy.data.actions):bpy.data.actions.remove(action)
for bone in rig.pose.bones:
    for constraint in list(bone.constraints):bone.constraints.remove(constraint)
    bone.rotation_mode='QUATERNION'
    # OGF ragdoll limits are not authoring IK limits. A rigid imported joint
    # otherwise locks the solver even though its target is valid.
    bone.lock_ik_x=bone.lock_ik_y=bone.lock_ik_z=False
    bone.use_ik_limit_x=bone.use_ik_limit_y=bone.use_ik_limit_z=False

rest={b.name:b.matrix_local.copy() for b in rig.data.bones}
order=sorted(rig.pose.bones,key=lambda b:len(b.parent_recursive))

def frame_at(name,position,rotation):
    result=rotation.to_matrix().to_4x4() @ rest[name].to_quaternion().to_matrix().to_4x4()
    result.translation=position
    return result

def limb(overrides,base,upper,lower,end,target,pole):
    # Solve using actual child pivots, rather than the artificial display
    # tails generated by the OGF importer. Segment lengths never stretch.
    start=(base @ rest[upper]).translation
    a=(rest[lower].translation-rest[upper].translation).length
    b=(rest[end].translation-rest[lower].translation).length
    axis=Vector(target)-start
    distance=max(abs(a-b)+.001,min(a+b-.001,axis.length))
    axis.normalize();finish=start+axis*distance
    along=(a*a-b*b+distance*distance)/(2*distance)
    height=math.sqrt(max(0,a*a-along*along))
    bend=Vector(pole)-start;bend-=axis*bend.dot(axis);bend.normalize()
    joint=start+axis*along+bend*height
    overrides[upper]=frame_at(upper,start,(rest[lower].translation-rest[upper].translation).rotation_difference(joint-start))
    overrides[lower]=frame_at(lower,joint,(rest[end].translation-rest[lower].translation).rotation_difference(finish-joint))
    overrides[end]=(base @ rest[end]).copy();overrides[end].translation=finish

samples=[]
frames=48
for grip in ('empty','knife','pistol','rifle'):
    for direction in ('idle','fwd','back','left','right'):
        action=bpy.data.actions.new('lz_prone_'+grip+'_'+direction)
        action.use_fake_user=True
        action.xray.fps=30;action.xray.speed=1
        rig.animation_data.action=action
        for frame in range(frames):
            bpy.context.scene.frame_set(frame)
            for bone in rig.pose.bones:bone.matrix_basis=Matrix.Identity(4)
            phase=frame/(frames-1)*math.tau
            moving=direction!='idle'
            wave=math.sin(phase) if moving else 0
            if direction=='back':wave=-wave
            base=Matrix.Translation((wave*.015,-.8,.31+(abs(wave)*.015 if moving else math.sin(phase)*.004))) @ Matrix.Rotation(-math.pi/2,4,'X')
            overrides={'bip01':base @ rest['bip01']}
            head=Matrix.Rotation(-math.radians(15),4,'X') @ rest['bip01_head'].to_quaternion().to_matrix().to_4x4()
            head.translation=(base @ rest['bip01_head']).translation;overrides['bip01_head']=head
            for side,sign in [('l',-1),('r',1)]:
                gait=wave*sign
                lateral=(.12*gait if direction in ('left','right') else 0)*(-1 if direction=='left' else 1)
                prefix='bip01_'+side+'_'
                limb(overrides,base,prefix+'thigh',prefix+'calf',prefix+'foot',
                     (sign*.17+lateral,-.58+gait*.10,.16+max(0,gait)*.035),(sign*.30,-.23,.08))
                if grip=='empty':hand=(sign*.32+lateral,.57-gait*.20,.09+max(0,-gait)*.05)
                elif side=='l' and moving and grip!='rifle':hand=(-.32+lateral,.52-gait*.18,.09+max(0,-gait)*.045)
                elif grip=='rifle':hand=(.04 if side=='l' else .12,1.0 if side=='l' else .68,.29)
                elif grip=='pistol':hand=(sign*.10,.91,.27)
                else:hand=(sign*.28,.62,.16)
                limb(overrides,base,prefix+'upperarm',prefix+'forearm',prefix+'hand',hand,(sign*.45,.30,.09))
                # Hold the weapon with its normal wrist grip; the left hand
                # supports crawling while the right keeps it above the ground.
                rotation=Matrix.Rotation(-math.radians(15 if grip=='empty' else 0),4,'X') @ rest[prefix+'hand'].to_quaternion().to_matrix().to_4x4()
                rotation.translation=overrides[prefix+'hand'].translation;overrides[prefix+'hand']=rotation
            poses={}
            for bone in order:
                parent=bone.parent
                poses[bone.name]=overrides.get(bone.name,poses[parent.name] @ rest[parent.name].inverted() @ rest[bone.name] if parent else rest[bone.name])
            for bone in order:
                parent=bone.parent
                kwargs={} if parent is None else dict(parent_matrix=poses[parent.name],parent_matrix_local=parent.bone.matrix_local)
                bone.matrix_basis=bone.bone.convert_local_to_pose(poses[bone.name],bone.bone.matrix_local,invert=True,**kwargs)
                bone.keyframe_insert('location',frame=frame)
                bone.keyframe_insert('rotation_quaternion',frame=frame)
                bone.keyframe_insert('scale',frame=frame)
            bpy.context.view_layer.update()
            if frame in (0,12,24,36):
                samples.append(dict(clip=action.name,frame=frame,bones={n:list(rig.pose.bones[n].matrix.translation) for n in ('bip01_head','bip01_pelvis','bip01_l_hand','bip01_r_hand','bip01_l_foot','bip01_r_foot')}))
        for curve in action.fcurves:
            for key in curve.keyframe_points:key.interpolation='LINEAR'
        item=rig.xray.motions_collection.add();item.name=action.name
for bone in rig.pose.bones:
    for constraint in list(bone.constraints):bone.constraints.remove(constraint)
bpy.ops.object.select_all(action='DESELECT');rig.select_set(True);bpy.context.view_layer.objects.active=rig
args.output.parent.mkdir(parents=True,exist_ok=True)
bpy.ops.wm.save_as_mainfile(filepath=str(args.output.with_suffix('.blend')))
result=bpy.ops.xray_export.omf_file(filepath=str(args.output))
assert result=={'FINISHED'} and args.output.exists()
args.output.with_suffix('.json').write_text(json.dumps(samples,indent=2)+'\n')
print('PRONE_EXPORTED',args.output,'clips',len(rig.xray.motions_collection),'samples',len(samples))
